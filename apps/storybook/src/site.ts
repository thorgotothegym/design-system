/**
 * The public name of the site. Everything visible derives from these constants: the page titles,
 * the meta and Open Graph tags, the welcome heading and the Open Graph image (regenerate it with
 * `pnpm --filter @aleixvidal/storybook brand-assets`). Renaming the site is a change here only;
 * the package (`@aleixvidal/ui`) and the repository keep their names.
 */
export const SITE = {
  name: "Console Forms",
  byline: "by Aleix Vidal",
  tagline: "Accessible form components",
  /** The canonical address: the vercel.app address must not compete with it in search results. */
  url: "https://design.aleixvidal.dev",
} as const;

/** The browser tab title and the Open Graph title. */
export const SITE_TITLE = `${SITE.name} - ${SITE.byline}`;

export const SITE_DESCRIPTION = `${SITE.tagline} for React, in a terminal style: design tokens, Radix and React Aria primitives, documented and tested in Storybook.`;

/** Served from apps/storybook/public; 1200 × 630, generated by scripts/brand-assets.ts. */
export const OG_IMAGE = {
  path: "/og-image.png",
  width: 1200,
  height: 630,
  alt: `${SITE.name}: ${SITE.tagline.toLowerCase()}, ${SITE.byline}`,
} as const;

const escapeAttribute = (value: string) =>
  value
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

/** The meta, canonical and social tags for the manager's `<head>` (see .storybook/main.ts). */
export const siteHeadTags = (themeColor: string) => {
  const image = `${SITE.url}${OG_IMAGE.path}`;
  const meta: [attribute: "name" | "property", key: string, value: string][] = [
    ["name", "description", SITE_DESCRIPTION],
    ["name", "theme-color", themeColor],
    ["property", "og:type", "website"],
    ["property", "og:site_name", SITE.name],
    ["property", "og:title", SITE_TITLE],
    ["property", "og:description", SITE_DESCRIPTION],
    ["property", "og:url", `${SITE.url}/`],
    ["property", "og:image", image],
    ["property", "og:image:width", String(OG_IMAGE.width)],
    ["property", "og:image:height", String(OG_IMAGE.height)],
    ["property", "og:image:alt", OG_IMAGE.alt],
    ["name", "twitter:card", "summary_large_image"],
    ["name", "twitter:title", SITE_TITLE],
    ["name", "twitter:description", SITE_DESCRIPTION],
    ["name", "twitter:image", image],
    ["name", "twitter:image:alt", OG_IMAGE.alt],
  ];

  return [
    `<link rel="canonical" href="${escapeAttribute(`${SITE.url}/`)}" />`,
    ...meta.map(
      ([attribute, key, value]) =>
        `<meta ${attribute}="${key}" content="${escapeAttribute(value)}" />`,
    ),
  ].join("\n");
};
